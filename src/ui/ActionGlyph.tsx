import type { PortalActionKind } from '../domain/types'

/**
 * Знаки четырёх действий смотрителя.
 *
 * Нужны не для украшения: четыре кнопки подряд различаются только текстом,
 * и на скорости человек читает первое слово, а не всю строку. Знак даёт
 * второй, более быстрый канал — форма узнаётся раньше, чем слово.
 *
 * Все нарисованы линиями в одной сетке 24×24 и одним ходом пера, чтобы
 * набор читался как один набор, а не как четыре случайные иконки.
 * Знак декоративен: рядом всегда есть подпись, поэтому aria-hidden.
 */
export function ActionGlyph({ kind }: { kind: PortalActionKind }) {
  return (
    <svg className="glyph" viewBox="0 0 24 24" aria-hidden="true">
      {kind === 'STABILIZE' && (
        // Контур, зажатый скобами: проём держат с двух сторон.
        <>
          <circle cx="12" cy="12" r="5.5" />
          <path d="M3 6.5 L3 3.5 L6 3.5 M18 3.5 L21 3.5 L21 6.5 M21 17.5 L21 20.5 L18 20.5 M6 20.5 L3 20.5 L3 17.5" />
          <path d="M9.5 12 L14.5 12" />
        </>
      )}

      {kind === 'SEND_OBSERVER' && (
        // Человек входит в арку: разведка — это шаг внутрь.
        <>
          <path d="M14 21 L14 7 A5 5 0 0 1 21 7 L21 21" />
          <path d="M6.5 21 L6.5 13" />
          <circle cx="6.5" cy="9" r="2.2" />
          <path d="M3.5 21 L9.5 21" />
        </>
      )}

      {kind === 'MARK_QUESTIONED' && (
        // Метка на полях: решение отложено, но не забыто.
        <>
          <path d="M5.5 21 L5.5 3 L18.5 3 L15 8.5 L18.5 14 L5.5 14" />
          <path d="M9.6 7.2 A1.9 1.9 0 1 1 11.5 9.3 L11.5 10.4" />
          <path d="M11.5 12.2 L11.5 12.3" />
        </>
      )}

      {kind === 'CLOSE' && (
        // Створки арки сходятся: управляемое схлопывание.
        <>
          <path d="M3.5 21 L3.5 9 A8.5 8.5 0 0 1 20.5 9 L20.5 21" />
          <path d="M8 21 L12 15 L16 21" />
          <path d="M12 15 L12 9.5" />
        </>
      )}
    </svg>
  )
}
