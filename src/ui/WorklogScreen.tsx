/**
 * Этап работы.
 *
 * Разбивка «что делал я / что делал AI / ключевой промпт» — не украшение,
 * а требование задания: worklog должен показывать это по каждому этапу,
 * а не общим списком в конце. Сверху остаётся, что вообще произошло;
 * остальное под раскрытием, иначе раздел превращается в стену текста.
 */
function Stage({
  title,
  text,
  human,
  ai,
  prompt,
  details,
}: {
  title: string
  text: string
  human: string
  ai: string
  prompt: string
  details?: ReactNode
}) {
  return (
    <li className="stage">
      <h4 className="stage__title">{title}</h4>
      <p className="stage__human">{text}</p>
      <details className="stage__more">
        <summary>Что делал я, что делал AI и по какому промпту</summary>
        <dl className="split">
          <div>
            <dt>Я</dt>
            <dd>{human}</dd>
          </div>
          <div>
            <dt>AI</dt>
            <dd>{ai}</dd>
          </div>
        </dl>
        <blockquote className="stage__prompt">{prompt}</blockquote>
        {details}
      </details>
    </li>
  )
}

