/**
 * Графика миров назначения.
 *
 * Девять миров — девять собственных силуэтов, нарисованных путями SVG.
 * Никаких внешних картинок, шрифтов и ссылок: всё рисуется кодом, весит
 * килобайты и одинаково выглядит в любом масштабе.
 *
 * Иллюстрация здесь не украшение: по силуэту и цвету мир узнаётся в списке
 * быстрее, чем по названию. Поэтому один и тот же путь используется и в
 * крупной сцене карточки, и в мелком знаке строки — форма запоминается.
 *
 * Система координат у всех сцен одна: viewBox 0 0 160 100, линия земли ≈ 84.
 */

export interface WorldArt {
  /** Верх и низ градиента неба. */
  sky: [string, string]
  /** Свечение над горизонтом — цвет портального света этого мира. */
  glow: string
  /** Дальний план. */
  far: string
  /** Ближний план: он же служит формой для мелкого знака. */
  near: string
  /** Мелкие акценты: снег, искры, сферы. */
  marks?: Array<{ x: number; y: number; r: number }>
  /** Как ведут себя акценты. */
  drift: 'rise' | 'fall' | 'float' | 'none'
}

